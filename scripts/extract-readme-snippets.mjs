// Extracts every ```ts / ```typescript block of README.md into test/types/readme.generated.ts so
// `npm run test:types` compiles the documentation. A block preceded by <!-- no-typecheck --> is skipped.
import { readFileSync, writeFileSync } from "node:fs";

const readme = readFileSync(new URL("../README.md", import.meta.url), "utf8");
const blocks = [];
const pattern = /(<!--\s*no-typecheck\s*-->\s*)?```(?:ts|typescript)\n([\s\S]*?)```/g;
for (const match of readme.matchAll(pattern)) {
  if (match[1]) continue;
  const line = readme.slice(0, match.index).split("\n").length;
  const code = match[2]
    .replace(/^import .*$/gm, "")
    .replace(/^export (?=const|function|type|interface|class)/gm, "")
    .trim();
  blocks.push(`// README.md:${line}\n{\n${code}\n}`);
}

const header = `// GENERATED by scripts/extract-readme-snippets.mjs — do not edit.
/* eslint-disable */
import create, { HttpRequest, RequestError, ResponseWrapper, createApi, createGet, createPost, isRequestError } from "../../src/index.js";
import type { ApiBuilder, ErrorInterceptor, FetchFunction, RequestConfig, RequestInterceptor, ResponseInterceptor, RetryConfig } from "../../src/index.js";
import { z } from "zod";
declare const token: string;
declare const id: string;
declare const url: string;
declare const signal: AbortSignal;
declare const form: HTMLFormElement;
declare const agent: import("undici").Agent;
declare const undiciFetch: typeof import("undici").fetch;
declare function refreshToken(): Promise<string>;
declare function render(value: unknown): void;
declare function showError(message: string): void;
declare function process(chunk: string): void;
declare function onProgress(fraction: number): void;
declare const useQuery: (options: { queryKey: unknown[]; queryFn: (context: { signal: AbortSignal }) => Promise<unknown> }) => unknown;
interface User { id: number; name: string; email?: string }
interface Post { id: number; title: string }
type Page<T> = { items: T[]; next: string | null };
declare const api: ApiBuilder;
void [create, HttpRequest, RequestError, ResponseWrapper, createApi, createGet, createPost, isRequestError, z, token, id, url, signal, form, agent, undiciFetch, refreshToken, render, showError, process, onProgress, useQuery, api];
export {};
async function __readme(): Promise<void> {
`;
writeFileSync(new URL("../test/types/readme.generated.ts", import.meta.url), `${header}${blocks.join("\n\n")}\n}\nvoid __readme;\n`);
console.log(`README: ${blocks.length} code blocks extracted for type-checking`);
