// Extracts the TypeScript code blocks of the documentation into files that `npm run test:types` compiles, so the
// examples cannot drift from the API:
// - every ```ts / ```typescript block of README.md → test/types/readme.generated.ts
//   (a block preceded by <!-- no-typecheck --> is skipped);
// - every ```ts / ```typescript block of a JSDoc comment in src/*.ts (the @example blocks editors show on hover)
//   → test/types/jsdoc.generated.ts.
// Each block becomes a scope of its own inside an async function, after a header that declares what the examples
// use without defining it (`token`, `api`, `User`, …).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const lineOf = (text, index) => text.slice(0, index).split("\n").length;
const scoped = (where, code) =>
  `// ${where}\n{\n${code
    .replace(/^import .*$/gm, "")
    .replace(/^export (?=const|function|type|interface|class)/gm, "")
    .trim()}\n}`;
const generate = (file, header, fn, blocks) =>
  writeFileSync(
    new URL(`../test/types/${file}`, import.meta.url),
    `// GENERATED by scripts/extract-snippets.mjs — do not edit.\n/* eslint-disable */\n${header}async function ${fn}(): Promise<void> {\n${blocks.join("\n\n")}\n}\nvoid ${fn};\n`
  );

// ------------------------------------------------------------------------------------------------- README.md
const readme = read("README.md");
const readmeBlocks = [];
for (const match of readme.matchAll(/(<!--\s*no-typecheck\s*-->\s*)?```(?:ts|typescript)\n([\s\S]*?)```/g)) {
  if (!match[1]) readmeBlocks.push(scoped(`README.md:${lineOf(readme, match.index)}`, match[2]));
}
generate(
  "readme.generated.ts",
  `import create, { HttpRequest, RequestError, ResponseWrapper, createApi, createGet, createPost, isRequestError } from "../../src/index.js";
import type { ApiBuilder, ErrorInterceptor, FetchFunction, RequestConfig, RequestInterceptor, ResponseInterceptor, RetryConfig } from "../../src/index.js";
import { z } from "zod";
declare const token: string;
declare const id: string;
declare const url: string;
declare const signal: AbortSignal;
declare const form: HTMLFormElement;
declare const agent: import("undici").Agent;
declare const undiciFetch: typeof import("undici").fetch;
declare function refreshToken(): Promise<string>;
declare function render(value: unknown): void;
declare function showError(message: string): void;
declare function handleChunk(chunk: string): void;
declare function onProgress(fraction: number): void;
declare const useQuery: (options: { queryKey: unknown[]; queryFn: (context: { signal: AbortSignal }) => Promise<unknown> }) => unknown;
interface User { id: number; name: string; email?: string }
interface Post { id: number; title: string }
type Page<T> = { items: T[]; next: string | null };
declare const api: ApiBuilder;
void [create, HttpRequest, RequestError, ResponseWrapper, createApi, createGet, createPost, isRequestError, z, token, id, url, signal, form, agent, undiciFetch, refreshToken, render, showError, handleChunk, onProgress, useQuery, api];
export {};
`,
  "__readme",
  readmeBlocks
);

// ---------------------------------------------------------------------------------------- JSDoc @example blocks
const jsdocBlocks = [];
for (const name of readdirSync(new URL("../src", import.meta.url))
  .filter(file => file.endsWith(".ts"))
  .sort()) {
  const source = read(`src/${name}`);
  for (const match of source.matchAll(/```(?:ts|typescript)\n([\s\S]*?)```/g)) {
    jsdocBlocks.push(scoped(`src/${name}:${lineOf(source, match.index)}`, match[1].replace(/^[ \t]*\* ?/gm, "")));
  }
}
generate(
  "jsdoc.generated.ts",
  `import create, { HttpRequest, RequestError, ResponseWrapper, createApi, isRequestError } from "../../src/index.js";
import type { ApiBuilder, ErrorInterceptor, RequestInterceptor, ResponseInterceptor, StandardSchemaV1 } from "../../src/index.js";
declare let token: string;
declare const id: string;
declare const url: string;
declare const form: HTMLFormElement;
declare const agent: import("undici").Agent;
declare const undiciFetch: typeof import("undici").fetch;
declare function refreshToken(): Promise<string>;
declare function render(value: unknown): void;
declare function showError(message: string): void;
declare function handleChunk(chunk: string): void;
declare const useQuery: (options: { queryKey: unknown[]; queryFn: (context: { signal: AbortSignal }) => Promise<unknown> }) => unknown;
interface User { id: number; name: string }
interface Issue { id: number; title: string }
type Page<T = User> = { items: T[]; users: T[] };
declare const UserSchema: StandardSchemaV1<unknown, User>;
declare const PageSchema: StandardSchemaV1<unknown, Page>;
declare const api: ApiBuilder;
declare const request: HttpRequest<"POST">;
declare const res: ResponseWrapper<Page>;
declare const user: User;
declare const error: RequestError;
void [create, HttpRequest, RequestError, ResponseWrapper, createApi, isRequestError, token, id, url, form, agent, undiciFetch, refreshToken, render, showError, handleChunk, useQuery, UserSchema, PageSchema, api, request, res, user, error];
export {};
`,
  "__jsdoc",
  jsdocBlocks
);

console.log(`${readmeBlocks.length} README code blocks and ${jsdocBlocks.length} JSDoc examples extracted for type-checking`);
